#!/bin/sh
# 构建 WebUI（Vite + Vue + TS）到 module/webroot，并写入源码指纹
# 用法: sh tools/build_webui.sh [repo-root]
set -eu
ROOT="${1:-.}"
UI="$ROOT/webui"
OUT="$ROOT/module/webroot"

[ -f "$UI/package.json" ] || { echo "no webui/package.json"; exit 1; }
command -v node >/dev/null 2>&1 || { echo "需要 node"; exit 1; }
command -v npm  >/dev/null 2>&1 || { echo "需要 npm"; exit 1; }

cd "$UI"
if [ ! -d node_modules ]; then
    echo "[i] 安装依赖（npm ci）"
    npm ci --no-audit --no-fund
fi
echo "[i] 类型检查 + 构建"
npm run build

# 源码指纹：与 check_zip.py 共用 tools/webui_fingerprint.py，避免两套算法漂移
_stamp_inputs=$(cd "$ROOT" && python tools/webui_fingerprint.py webui)
cat > "$OUT/.build.json" <<JSON
{
  "generator": "vite+vue+ts",
  "source_sha256": "$_stamp_inputs",
  "note": "generated by tools/build_webui.sh; do not edit"
}
JSON
echo "[+] webroot 已生成：$OUT"
du -sh "$OUT" 2>/dev/null || true
