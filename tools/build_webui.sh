#!/bin/sh
# 构建 WebUI（Vite + Vue + TS）到 module/webroot，并写入源码指纹
# 用法: sh tools/build_webui.sh [repo-root]      # 在仓库根目录直接跑，无需参数
set -eu

# 解析成绝对路径：脚本会 cd 到 webui/，相对路径会随之失效
ROOT=$(cd "${1:-.}" && pwd)
UI="$ROOT/webui"
OUT="$ROOT/module/webroot"

[ -f "$UI/package.json" ] || { echo "no webui/package.json (ROOT=$ROOT)"; exit 1; }
command -v node >/dev/null 2>&1 || { echo "需要 node"; exit 1; }
command -v npm >/dev/null 2>&1 || { echo "需要 npm"; exit 1; }

# 构建前先算源码指纹：构建中途失败时不会把新指纹盖到旧产物上
STAMP=$(python "$ROOT/tools/webui_fingerprint.py" "$UI") || { echo "指纹计算失败"; exit 1; }

# 备份上一份产物：vite 构建开始时会清空 outDir，失败后不能留下残缺目录
BAK="$ROOT/.webui-backup.$$"
HAD_OUT=0
if [ -d "$OUT" ]; then
    cp -a "$OUT" "$BAK" 2>/dev/null && HAD_OUT=1 || { echo "备份旧产物失败"; exit 1; }
fi
cleanup() { rm -rf "$BAK"; }
trap cleanup EXIT INT TERM

cd "$UI"
if [ ! -d node_modules ]; then
    echo "[i] 安装依赖（npm ci）"
    npm ci --no-audit --no-fund
fi

echo "[i] 类型检查 + 构建"
if ! npm run build; then
    echo "[!] 构建失败，恢复上一份产物"
    rm -rf "$OUT"
    if [ "$HAD_OUT" = "1" ] && [ -d "$BAK" ]; then
        mv -f "$BAK" "$OUT"
        trap - EXIT INT TERM
    fi
    exit 1
fi

cat > "$OUT/.build.json" <<JSON
{
  "generator": "vite+vue+ts",
  "source_sha256": "$STAMP",
  "note": "generated by tools/build_webui.sh; do not edit"
}
JSON
echo "[+] webroot 已生成：$OUT"
du -sh "$OUT" 2>/dev/null || true
